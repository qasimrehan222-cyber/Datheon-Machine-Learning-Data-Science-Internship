sns.heatmap(df_fe.select_dtypes(include=[np.number]).corr(), annot=True, fmt=".2f", cmap="coolwarm", linewidths=0.5)
plt.title("Correlation Heatmap (Including Target & Engineered Features)", fontsize=13)
